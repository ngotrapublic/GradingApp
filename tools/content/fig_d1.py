import schemdraw, schemdraw.elements as elm, matplotlib
matplotlib.use('Agg')
schemdraw.config(fontsize=16, lw=2)
with schemdraw.Drawing(file='/Users/mac/Tra/SE9_ElecCircuitLab/HCM/GradingApp/tools/content/fig/d1_circuit.png', dpi=220, show=False) as d:
    elm.SourceV().up().length(4).label('5 V', loc='bottom', ofst=0.3)
    w=elm.Line().right(2)
    elm.CurrentLabel(top=True, ofst=0.25, length=1.2).at(w).label('I')
    top=d.here; elm.Dot()
    elm.Line().up(1.25)
    ra=elm.Resistor().right(4).label('$R_A$')
    elm.CurrentLabel(top=False, ofst=0.25).at(ra).label('$I_A$')
    elm.Line().down(1.25); elm.Dot()
    elm.Line().at(top).down(1.25)
    elm.Resistor().right(4).label('$R_B$', loc='bottom')
    elm.Line().up(1.25)
    elm.Line().right(2)
    elm.Dot().label('X', loc='top')
    elm.Resistor().down(2).label('$R_C$')
    elm.Resistor().down(2).label('$R_D$')
    elm.Line().left(8)
    elm.Ground().at((0,0))
    elm.Label().at((4,-0.2)).label('0 V', loc='bottom')
